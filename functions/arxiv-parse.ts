const NAMED_ENTITIES: Record<string, string> = {
  amp: "&",
  lt: "<",
  gt: ">",
  quot: '"',
  apos: "'",
  nbsp: " ",
  ndash: "\u2013",
  mdash: "\u2014",
  hellip: "\u2026",
  lsquo: "\u2018",
  rsquo: "\u2019",
  ldquo: "\u201c",
  rdquo: "\u201d",
  times: "\u00d7",
  middot: "\u00b7",
};

function decodeEntities(text: string): string {
  return text.replace(/&(#x?[0-9a-fA-F]+|[a-zA-Z][a-zA-Z0-9]*);/g, (whole, body: string) => {
    if (body.startsWith("#x") || body.startsWith("#X")) {
      const code = Number.parseInt(body.slice(2), 16);
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    if (body.startsWith("#")) {
      const code = Number.parseInt(body.slice(1), 10);
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    const named = NAMED_ENTITIES[body.toLowerCase()];
    return named ?? whole;
  });
}

/**
 * LaTeX is kept verbatim and wrapped in `$…$`.
 *
 * Not converted to Unicode approximations: a lossy `d_{k}` → `dₖ` rewrite would
 * silently corrupt exactly the expressions a reader most needs to be right.
 * `$…$` is unambiguous, is what the model understands when the reader asks for
 * an explanation, and stays identical in the DOM so text-fingerprint anchoring
 * of highlights keeps working after a reload.
 */
function replaceMathWithLatex(fragment: string): string {
  let out = "";
  let cursor = 0;
  const openRe = /<math\b[^>]*>/g;
  for (;;) {
    openRe.lastIndex = cursor;
    const hit = openRe.exec(fragment);
    if (!hit) {
      out += fragment.slice(cursor);
      return out;
    }
    const end = balancedEnd(fragment, hit.index, "math");
    const alt = /\balttext="([^"]*)"/.exec(hit[0]);
    // alttext is the LaTeX; the annotation element carries the same string.
    const latex = decodeEntities(alt?.[1] ?? "").trim();
    out += fragment.slice(cursor, hit.index);
    out += latex ? ` $${latex}$ ` : " ";
    cursor = end;
  }
}

/** Turn an HTML fragment into the single-line reading text shown to the user. */
export function htmlToReadingText(fragment: string): string {
  let text = replaceMathWithLatex(fragment);
  // Citations and cross-references render as bare bracketed numbers; dropping
  // the tag but keeping the text preserves "[12]" style references.
  text = text.replace(/<[^>]+>/g, " ");
  text = decodeEntities(text);
  return (
    text
      .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, "")
      .replace(/\s+/g, " ")
      // Every removed tag became a space, which leaves debris around citations
      // and inline math: "[ 13 ] ." or "$d_{k}$ ,". Rejoin punctuation without
      // touching real word gaps. A space before a comma is never correct prose,
      // so this cannot corrupt the authors' meaning.
      .replace(/\s+([,.;:!?])/g, "$1")
      .replace(/([([])\s+/g, "$1")
      .replace(/\s+([)\]])/g, "$1")
      // "-dimensional" style suffixes that follow an inline math span.
      .replace(/\$ -(?=[A-Za-z])/g, "$$-")
      .trim()
  );
}

