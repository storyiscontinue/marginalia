/** Attribute reader that tolerates single quotes and missing attributes. */
function attr(openTag: string, name: string): string {
  const re = new RegExp(`\\b${name}\\s*=\\s*("([^"]*)"|'([^']*)')`, "i");
  const hit = re.exec(openTag);
  if (!hit) return "";
  return decodeEntities(hit[2] ?? hit[3] ?? "").trim();
}

function hasClass(openTag: string, className: string): boolean {
  const value = attr(openTag, "class");
  return value.split(/\s+/).includes(className);
}

/* ------------------------------------------------------------------ */
/* Linear token scan                                                   */
/* ------------------------------------------------------------------ */

type Token =
  | { kind: "section_open"; id: string; level: number; titling: boolean }
  | { kind: "section_close" }
  | { kind: "title"; level: number; html: string }
  | { kind: "para"; id: string; html: string }
  | { kind: "equation"; id: string; latex: string; label: string; numbered: boolean };

interface SectionFrame {
  id: string;
  level: number;
  title: string;
  /**
   * False for LaTeXML's `ltx_paragraph` — a bold run-in heading such as
   * "Encoder:" or "Label Smoothing" that sits inside a numbered section. It is
   * real markup but it is not a navigable section, so it must never appear in
   * the spine or reset the current section.
   */
  titling: boolean;
}

/**
 * One forward pass over the cleaned document.
 *
 * A single alternation regex is used only to find *start* positions; the
 * element bodies are then taken with balancedEnd, so nested tables inside an
 * equation group and nested spans inside a title cannot truncate a match.
 */
function tokenize(html: string): Token[] {
  const tokens: Token[] = [];
  const scan =
    /<(section|h2|h3|h4|h5|h6|p|table)\b([^>]*)>|<\/section>/g;

  let match: RegExpExecArray | null;
  while ((match = scan.exec(html)) !== null) {
    if (match[0] === "</section>") {
      tokens.push({ kind: "section_close" });
      continue;
    }

    const tag = match[1].toLowerCase();
    const openTag = match[0];
    const bodyEnd = balancedEnd(html, match.index, tag);

    if (tag === "section") {
      const classes = attr(openTag, "class").split(/\s+/);
      const level = classes.includes("ltx_subsubsection")
        ? 4
        : classes.includes("ltx_subsection")
          ? 3
          : classes.includes("ltx_section")
            ? 2
            : 0;
      const titling = level >= 2;
      tokens.push({ kind: "section_open", id: attr(openTag, "id"), level, titling });
      // Do not skip the body: nested sections and paragraphs live inside it.
      scan.lastIndex = match.index + openTag.length;
      continue;
    }

    const inner = html.slice(match.index + openTag.length, bodyEnd - `</${tag}>`.length);

    if (tag === "h2" || tag === "h3" || tag === "h4" || tag === "h5" || tag === "h6") {
      if (hasClass(openTag, "ltx_title")) {
        tokens.push({ kind: "title", level: Number(tag[1]), html: inner });
      }
      scan.lastIndex = bodyEnd;
      continue;
    }

    if (tag === "p") {
      if (hasClass(openTag, "ltx_p")) {
        tokens.push({ kind: "para", id: attr(openTag, "id"), html: inner });
      }
      scan.lastIndex = bodyEnd;
      continue;
    }

    // tag === "table"
    if (hasClass(openTag, "ltx_equation") || hasClass(openTag, "ltx_equationgroup")) {
      const numbered = hasClass(openTag, "ltx_equation");
      const found = extractDisplayEquation(inner);
      if (found) {
        tokens.push({
          kind: "equation",
          id: attr(openTag, "id"),
          latex: found.latex,
          label: found.label,
          numbered,
        });
      }
    }
    // Either way the table body is consumed, so its cells never leak in as text.
    scan.lastIndex = bodyEnd;
  }

  return tokens;
}

/** First `alttext` inside an equation table — that is the displayed LaTeX. */
function extractDisplayEquation(inner: string): { latex: string; label: string } | null {
  // The paper's own equation number, when it has one. Unnumbered displays
  // (`ltx_equationgroup`) simply have no such cell, and get no invented label.
  const tag = /<span\b[^>]*class="[^"]*\bltx_tag_equation\b[^"]*"[^>]*>([\s\S]*?)<\/span>/.exec(inner);
  const label = tag ? htmlToReadingText(tag[1]).slice(0, 12) : "";

  // An `align` group splits one logical display across <tr> rows, and each row
  // splits its left and right halves across <td> cells. Concatenating alttext
  // within a row reassembles the expression; a newline between rows keeps the
  // authors' own layout instead of welding "…W^O" onto "where head_i = …".
  const rows: string[] = [];
  const rowRe = /<tr\b[^>]*>([\s\S]*?)<\/tr>/g;
  let row: RegExpExecArray | null;
  while ((row = rowRe.exec(inner)) !== null) {
    const parts: string[] = [];
    const mathRe = /<math\b[^>]*\balttext="([^"]*)"/g;
    let math: RegExpExecArray | null;
    while ((math = mathRe.exec(row[1])) !== null) {
      const tex = decodeEntities(math[1]).trim();
      if (tex) parts.push(tex);
    }
    if (parts.length > 0) rows.push(parts.join(""));
  }

  const latex = rows.join("\n").trim();
  return latex.length > 0 ? { latex: latex.slice(0, 2000), label } : null;
}

