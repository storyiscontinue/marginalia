/**
 * Index just past the `</tag>` matching the element that starts at `openStart`.
 *
 * Regex cannot match balanced nesting, and LaTeXML nests `span`, `div`, `table`
 * and `section` freely. Counting open/close pairs is sufficient here because
 * none of these tags are ever self-closing in LaTeXML output, and any `<` in
 * text content is entity-encoded as `&lt;`.
 */
function balancedEnd(html: string, openStart: number, tag: string): number {
  const openRe = new RegExp(`<${tag}(?=[\\s>/])`, "g");
  const closeRe = new RegExp(`</${tag}>`, "g");
  let depth = 0;
  let i = openStart;
  for (;;) {
    openRe.lastIndex = i;
    closeRe.lastIndex = i;
    const nextOpen = openRe.exec(html);
    const nextClose = closeRe.exec(html);
    if (!nextClose) return html.length;
    if (nextOpen && nextOpen.index < nextClose.index) {
      depth += 1;
      i = nextOpen.index + nextOpen[0].length;
      continue;
    }
    depth -= 1;
    i = nextClose.index + nextClose[0].length;
    if (depth <= 0) return i;
  }
}

/** Remove every element whose start tag matches `matcher`. Returns new HTML. */
function stripElements(html: string, matcher: RegExp, tag: string): string {
  let out = html;
  // Each removal shifts indices, so restart the scan every time. Bounded by the
  // number of matches; LaTeXML documents have few hundred at most.
  for (let guard = 0; guard < 5000; guard += 1) {
    matcher.lastIndex = 0;
    const hit = matcher.exec(out);
    if (!hit) return out;
    const end = balancedEnd(out, hit.index, tag);
    out = out.slice(0, hit.index) + out.slice(end);
  }
  return out;
}

