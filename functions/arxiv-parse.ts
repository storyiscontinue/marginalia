function extractTitle(html: string): string {
  const hit = /<h1\b[^>]*class="[^"]*\bltx_title_document\b[^"]*"[^>]*>/.exec(html);
  if (!hit) return "";
  const end = balancedEnd(html, hit.index, "h1");
  return htmlToReadingText(html.slice(hit.index + hit[0].length, end - "</h1>".length)).slice(0, 400);
}

function extractAuthors(html: string): string {
  const hit = /<div\b[^>]*class="[^"]*\bltx_authors\b[^"]*"[^>]*>/g;
  hit.lastIndex = 0;
  const open = hit.exec(html);
  if (!open) return "";
  const end = balancedEnd(html, open.index, "div");
  let block = html.slice(open.index, end);

  // Author names carry "Equal contribution" thanks-notes and footnote marks as
  // nested spans. They are real markup but they are not part of a byline, and
  // leaving them in produces "Noam Shazeer 1 1 footnotemark: 1".
  block = stripElements(block, /<span\b[^>]*class="[^"]*\bltx_note\b[^"]*"[^>]*>/g, "span");
  block = stripElements(block, /<span\b[^>]*class="[^"]*\bltx_note_outer\b[^"]*"[^>]*>/g, "span");
  block = block.replace(/<sup\b[^>]*>[\s\S]*?<\/sup>/g, " ");

  const names: string[] = [];
  const personRe = /<span\b[^>]*class="[^"]*\bltx_personname\b[^"]*"[^>]*>/g;
  let m: RegExpExecArray | null;
  while ((m = personRe.exec(block)) !== null && names.length < MAX_AUTHORS) {
    const stop = balancedEnd(block, m.index, "span");
    let inner = block.slice(m.index + m[0].length, stop - "</span>".length);
    // Affiliations and ORCID links are not part of a readable byline either.
    inner = stripElements(inner, /<span\b[^>]*class="[^"]*\bltx_contact\b[^"]*"[^>]*>/g, "span");
    inner = stripElements(inner, /<a\b[^>]*>/g, "a");
    const name = htmlToReadingText(inner);
    if (name && !names.includes(name)) names.push(name);
    personRe.lastIndex = stop;
  }
  return names.join(", ").slice(0, 1200);
}

/** `arXiv:1706.03762v7 [cs.CL] 02 Aug 2023` → version, category, date. */
function extractWatermark(html: string): { version: string; primaryCategory: string; dateText: string } {
  const hit = /arXiv:\s*([0-9]{4}\.[0-9]{4,5})(v[0-9]{1,3})?\s*\[([^\]]{1,40})\]\s*([0-9]{1,2}\s+[A-Za-z]{3}\s+[0-9]{4})/.exec(
    html.replace(/<[^>]+>/g, " "),
  );
  if (!hit) return { version: "", primaryCategory: "", dateText: "" };
  return { version: hit[2] ?? "", primaryCategory: hit[3].trim(), dateText: hit[4].trim() };
}

function extractAbstract(html: string): string {
  const hit = /<div\b[^>]*class="[^"]*\bltx_abstract\b[^"]*"[^>]*>/.exec(html);
  if (!hit) return "";
  const end = balancedEnd(html, hit.index, "div");
  const block = html.slice(hit.index, end);
  const parts: string[] = [];
  const paraRe = /<p\b([^>]*)>([\s\S]*?)<\/p>/g;
  let m: RegExpExecArray | null;
  while ((m = paraRe.exec(block)) !== null) {
    if (!hasClass(m[0], "ltx_p")) continue;
    const text = htmlToReadingText(m[2]);
    if (text) parts.push(text);
  }
  return parts.join(" ").slice(0, 6000);
}

