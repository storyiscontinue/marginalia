/**
 * Parse one arXiv LaTeXML HTML document.
 *
 * `arxivId` is used only to label the result; callers must have validated it
 * before fetching, because it is what selected the upstream URL.
 */
export function parseLatexml(html: string, arxivId: string): ParseResult {
  if (typeof html !== "string" || html.length === 0) {
    return { ok: false, code: "not_latexml" };
  }
  // Cheap authenticity gate: refuse to guess at markup from some other tool.
  if (!html.includes("ltx_document") && !html.includes("Generated by LaTeXML")) {
    return { ok: false, code: "not_latexml" };
  }

  const title = extractTitle(html);
  if (!title) return { ok: false, code: "title_missing" };

  // Cut the reference list and everything after it (LaTeXML puts appendices
  // past the bibliography, and neither belongs in a first-read pass).
  const bibAt = html.search(/<section\b[^>]*class="[^"]*\bltx_bibliography\b/);
  let body = bibAt > 0 ? html.slice(0, bibAt) : html;

  // Footnote bodies, figures and data tables are removed before tokenizing so
  // their text can never be mistaken for something the reader should read.
  body = stripElements(body, /<script\b[^>]*>/g, "script");
  body = stripElements(body, /<style\b[^>]*>/g, "style");
  body = stripElements(body, /<span\b[^>]*class="[^"]*\bltx_note\b[^"]*"[^>]*>/g, "span");
  body = stripElements(body, /<span\b[^>]*class="[^"]*\bltx_note_outer\b[^"]*"[^>]*>/g, "span");
  body = stripElements(body, /<figure\b[^>]*>/g, "figure");
  body = stripElements(body, /<div\b[^>]*class="[^"]*\bltx_page_navbar\b[^"]*"[^>]*>/g, "div");
  body = stripElements(body, /<div\b[^>]*class="[^"]*\bltx_toc\b[^"]*"[^>]*>/g, "div");
  body = stripElements(body, /<nav\b[^>]*>/g, "nav");
  // The abstract is emitted as unit 1 from its own extraction, so removing it
  // here is what stops it appearing twice.
  body = stripElements(body, /<div\b[^>]*class="[^"]*\bltx_abstract\b[^"]*"[^>]*>/g, "div");
  // arXiv's own front matter: the reproduction-permission notice and the
  // watermark are not the authors' words.
  body = stripElements(body, /<div\b[^>]*id="p1"[^>]*>/g, "div");
  body = stripElements(body, /<div\b[^>]*id="watermark[^"]*"[^>]*>/g, "div");

  const abstract = extractAbstract(html);
  const authors = extractAuthors(html);
  const watermark = extractWatermark(html);

  const units: ParsedUnit[] = [];
  const formulas: ParsedFormula[] = [];
  const sectionOrderById = new Map<string, number>();
  const stack: SectionFrame[] = [];
  let currentSection = "";
  let currentSectionOrder = 1;
  let lastUnitId = "";
  let truncated = false;
  /** Counter for numbered displays, used only if arXiv omits the number cell. */
  let numberedSeen = 0;

  // The abstract is unit 1 so a reader always lands on text they can select.
  if (abstract && abstract.length >= MIN_UNIT_CHARS) {
    const id = `u-abstract-${arxivId}`;
    sectionOrderById.set("Abstract", 1);
    units.push({
      id,
      order: 1,
      section: "Abstract",
      sectionOrder: 1,
      original: abstract.slice(0, MAX_UNIT_CHARS),
      formulaIds: [],
    });
    lastUnitId = id;
    currentSection = "Abstract";
    currentSectionOrder = 1;
  }

  for (const token of tokenize(body)) {
    if (token.kind === "section_open") {
      stack.push({ id: token.id, level: token.level, title: "", titling: token.titling });
      continue;
    }

    if (token.kind === "section_close") {
      stack.pop();
      continue;
    }

    if (token.kind === "title") {
      // Attach to the innermost section that has not been titled yet. Assigning
      // it also consumes the heading, so a run-in "Encoder:" can never leak
      // into the following paragraph's text.
      for (let i = stack.length - 1; i >= 0; i -= 1) {
        if (!stack[i].title) {
          stack[i].title = htmlToReadingText(token.html).slice(0, 200);
          break;
        }
      }
      const frame = stack[stack.length - 1];
      if (frame && frame.titling && frame.title) {
        currentSection = frame.title;
        const known = sectionOrderById.get(currentSection);
        if (known === undefined) {
          currentSectionOrder = sectionOrderById.size + 1;
          sectionOrderById.set(currentSection, currentSectionOrder);
        } else {
          currentSectionOrder = known;
        }
      }
      continue;
    }

    if (token.kind === "equation") {
      if (formulas.length >= MAX_FORMULAS) {
        truncated = true;
        continue;
      }
      const id = `f-${token.id || formulas.length + 1}`;
      let label = token.label;
      if (!label && token.numbered) {
        // The number cell was missing; fall back to the order numbered displays
        // appear in, which is the order the paper numbers them.
        numberedSeen += 1;
        label = `(${numberedSeen})`;
      } else if (token.numbered) {
        const digits = /[0-9]+/.exec(label);
        if (digits) numberedSeen = Number(digits[0]);
      }
      formulas.push({
        id,
        label,
        latex: token.latex,
        unicode: latexToReadable(token.latex),
        unitId: lastUnitId,
      });
      const owner = units.find((unit) => unit.id === lastUnitId);
      if (owner && owner.formulaIds.length < 12) owner.formulaIds.push(id);
      continue;
    }

    // token.kind === "para"
    if (units.length >= MAX_UNITS) {
      truncated = true;
      break;
    }

    const text = htmlToReadingText(token.html);
    if (text.length < MIN_UNIT_CHARS) continue;
    if (!/[A-Za-z]/.test(text)) continue; // pure-math or pure-symbol blocks

    const paraId = token.id || `p${units.length + 1}`;
    const id = `u-${paraId}`;
    units.push({
      id,
      order: units.length + 1,
      section: currentSection || "正文",
      sectionOrder: currentSectionOrder,
      original: text.length > MAX_UNIT_CHARS ? text.slice(0, MAX_UNIT_CHARS) : text,
      formulaIds: [],
    });
    if (text.length > MAX_UNIT_CHARS) truncated = true;
    lastUnitId = id;
  }

  if (units.length === 0) return { ok: false, code: "no_readable_units" };

  return {
    ok: true,
    paper: {
      arxivId,
      version: watermark.version,
      title,
      authors,
      primaryCategory: watermark.primaryCategory,
      dateText: watermark.dateText,
      abstract,
      units,
      formulas,
      truncated,
    },
  };
}

/**
 * Strict arXiv identifier validation.
 *
 * The returned value is interpolated into an upstream URL, so this is the only
 * thing standing between a public request and an open redirect. Accepts
 * `1706.03762` and `1706.03762v7`; rejects everything else, including the
 * legacy `math/0211159` form, which is not worth the URL-shape ambiguity.
 */
export function normalizeArxivId(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const trimmed = raw.trim().toLowerCase();
  const match = /^([0-9]{4}\.[0-9]{4,5})(v([1-9][0-9]{0,2}))?$/.exec(trimmed);
  if (!match) return null;
  return match[3] ? `${match[1]}v${match[3]}` : match[1];
}
