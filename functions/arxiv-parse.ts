/** Macros that only decorate or size their argument; the argument is what matters. */
const DECORATORS =
  /\\(?:mathrm|mathit|mathbf|mathsf|mathtt|mathcal|mathbb|text|textrm|textbf|textit|operatorname|mbox|hat|bar|overline|underline|vec|tilde|widetilde|dot|ddot|tilde|overset|underset)\s*\{/g;

/** `\mathrm{X}` / `\text{X}` / `\hat{X}` → X, innermost-safe and repeated. */
function unwrapTextMacros(latex: string): string {
  let out = latex;
  for (let guard = 0; guard < 40; guard += 1) {
    DECORATORS.lastIndex = 0;
    const hit = DECORATORS.exec(out);
    if (!hit) return out;
    const braceStart = hit.index + hit[0].length - 1;
    const contentEnd = matchingBrace(out, braceStart);
    if (contentEnd < 0) return out;
    out = out.slice(0, hit.index) + out.slice(braceStart + 1, contentEnd) + out.slice(contentEnd + 1);
  }
  return out;
}

/** Index of the `}` matching the `{` at `start`, honouring nesting. */
function matchingBrace(text: string, start: number): number {
  let depth = 0;
  for (let i = start; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === "\\") {
      i += 1;
      continue;
    }
    if (ch === "{") depth += 1;
    else if (ch === "}") {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
}

function mapScript(body: string, table: Record<string, string>): string | null {
  let out = "";
  for (const ch of body) {
    const mapped = table[ch];
    if (!mapped) return null;
    out += mapped;
  }
  return out;
}

/**
 * How to write a script when Unicode has no glyph for it.
 *
 * Parenthesising is not cosmetic: `10000^2i/d_model` would be read as
 * (10000^2i)/d_model, which is a different expression from the paper's
 * 10000^(2i/d_model). A compound body must be grouped or it changes meaning.
 */
function scriptFallback(marker: string, body: string): string {
  const simple = /^[A-Za-z0-9]{1,6}$/.test(body);
  const alreadyGrouped = body.startsWith("(") && body.endsWith(")");
  return simple || alreadyGrouped ? `${marker}${body}` : `${marker}(${body})`;
}

/** `_{...}` and `^{...}` → Unicode scripts, or a plain `_x` when no glyph exists. */
function convertScripts(latex: string, marker: "_" | "^", table: Record<string, string>): string {
  let out = latex;
  const bareRe = new RegExp(`\\${marker}(?=[A-Za-z0-9])`);

  // Single-character form first. Running the braced form first would leave a
  // fallback such as `_model` in the string, whose leading `_m` the bare pass
  // would then re-match and mangle into `ₘodel`.
  for (let guard = 0; guard < 80; guard += 1) {
    const hit = bareRe.exec(out);
    if (!hit) break;
    const ch = out[hit.index + 1];
    out = out.slice(0, hit.index) + (table[ch] ?? `${marker}${ch}`) + out.slice(hit.index + 2);
  }

  for (let guard = 0; guard < 80; guard += 1) {
    const idx = out.indexOf(`${marker}{`);
    if (idx < 0) break;
    const braceStart = idx + 1;
    const end = matchingBrace(out, braceStart);
    if (end < 0) break;
    const body = out.slice(braceStart + 1, end);
    const mapped = mapScript(body, table);
    out = out.slice(0, idx) + (mapped ?? scriptFallback(marker, body)) + out.slice(end + 1);
  }

  return out;
}

/** `\sqrt{X}` → `√X`, parenthesising only a compound radicand. */
function convertRoots(latex: string): string {
  let out = latex;
  for (let guard = 0; guard < 30; guard += 1) {
    const idx = out.indexOf("\\sqrt{");
    if (idx < 0) break;
    const braceStart = idx + 5;
    const end = matchingBrace(out, braceStart);
    if (end < 0) break;
    const body = out.slice(braceStart + 1, end);
    out = out.slice(0, idx) + `√${body.length <= 3 ? body : `(${body})`}` + out.slice(end + 1);
  }
  return out.replace(/\\sqrt(?![A-Za-z])/g, "√");
}

/** `\frac{A}{B}` → `A ⁄ B`, parenthesising only when a side is compound. */
function convertFractions(latex: string): string {
  let out = latex;
  for (let guard = 0; guard < 30; guard += 1) {
    const re = /\\(?:frac|dfrac|tfrac|cfrac)\s*\{/g;
    re.lastIndex = 0;
    const hit = re.exec(out);
    if (!hit) return out;
    const numOpen = hit.index + hit[0].length - 1;
    const numClose = matchingBrace(out, numOpen);
    if (numClose < 0) return out;
    const numerator = out.slice(numOpen + 1, numClose);

    const denOpen = out.indexOf("{", numClose + 1);
    if (denOpen < 0) return out;
    const denClose = matchingBrace(out, denOpen);
    if (denClose < 0) return out;
    const denominator = out.slice(denOpen + 1, denClose);

    const wrap = (side: string) => (side.length <= 3 && !/[+±]/.test(side) ? side : `(${side})`);
    out = out.slice(0, hit.index) + `${wrap(numerator)} ⁄ ${wrap(denominator)}` + out.slice(denClose + 1);
  }
  return out;
}

/**
 * Render LaTeX as readable plain text.
 *
 * Best effort by design and never the only copy: `ParsedFormula.latex` keeps the
 * verbatim source, so an imperfect rendering can always be checked against it.
 * Anything unrecognised is passed through rather than dropped, because a
 * silently omitted term is worse than a visible `\foo`.
 *
 * Pass order is load-bearing: scripts are converted before roots and fractions
 * so that `\frac{QK^{T}}{\sqrt{d_{k}}}` is measured as `QKᵀ ⁄ √dₖ` — already
 * short — instead of being wrapped in parentheses that the source never had.
 */
export function latexToReadable(latex: string): string {
  let out = typeof latex === "string" ? latex : "";
  out = out
    .replace(/\\displaystyle(?![A-Za-z])/g, "")
    .replace(/\\textstyle(?![A-Za-z])/g, "")
    .replace(/\\script(?:script)?style(?![A-Za-z])/g, "")
    .replace(/\\no?limits(?![A-Za-z])/g, "")
    .replace(/\\left\s*/g, "")
    .replace(/\\right\s*/g, "")
    .replace(/\\[bB]igg?[lrm]?\s*/g, "")
    .replace(/\\middle\s*/g, "");

  out = unwrapTextMacros(out);
  out = out.replace(/\\([%&_#$])/g, "$1");
  out = out.replace(/\\\\/g, " ");
  out = out.replace(/\\arg\s*(max|min)/g, "arg$1");

  for (const [re, replacement] of SYMBOLS) out = out.replace(re, replacement);
  out = out.replace(
    /\\(?:sin|cos|tan|cot|sec|csc|arcsin|arccos|arctan|log|ln|lg|exp|max|min|sup|inf|lim|limsup|liminf|det|dim|ker|deg|gcd|Pr|arg)(?![A-Za-z])/g,
    (m) => m.slice(1),
  );

  out = convertScripts(out, "^", SUPERSCRIPTS);
  out = convertScripts(out, "_", SUBSCRIPTS);
  out = convertRoots(out);
  out = convertFractions(out);

  return (
    out
      .replace(/[{}]/g, "")
      // Horizontal whitespace only. A newline separates the rows of an align
      // group and must survive, or "…W^O" welds onto "where head_i = …".
      .replace(/[ \t]*=[ \t]*/g, " = ")
      .replace(/([·×])[ \t]+/g, "$1")
      .replace(/[ \t]+([,.;:])/g, "$1")
      .replace(/[ \t]+/g, " ")
      .split("\n")
      .map((line) => line.trim())
      .filter((line) => line.length > 0)
      .join("\n")
  );
}

